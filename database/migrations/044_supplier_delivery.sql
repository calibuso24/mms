CREATE OR REPLACE FUNCTION post_supplier_delivery(
    p_supplier_delivery_id BIGINT,
    p_posted_by_account_id BIGINT DEFAULT NULL
)
RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
    v_sd supplier_delivery%ROWTYPE;
    v_po purchase_order%ROWTYPE;
    v_item RECORD;
    v_status_draft_id BIGINT;
    v_status_posted_id BIGINT;
    v_po_status_approved_id BIGINT;
    v_po_status_partial_id BIGINT;
    v_po_status_delivered_id BIGINT;
    v_movement_type_receipt_id BIGINT;
    v_movement_status_completed_id BIGINT;
    v_remaining_qty NUMERIC;
    v_movement_id BIGINT;
    v_item_count BIGINT := 0;
    v_posted_item_count BIGINT := 0;
    v_has_remaining BOOLEAN;
BEGIN
    SELECT look_up_id
    INTO v_status_draft_id
    FROM look_up
    WHERE look_up_type = 'supplier_delivery_status'
      AND code = 'draft';

    SELECT look_up_id
    INTO v_status_posted_id
    FROM look_up
    WHERE look_up_type = 'supplier_delivery_status'
      AND code = 'posted';

    SELECT look_up_id
    INTO v_po_status_approved_id
    FROM look_up
    WHERE look_up_type = 'purchase_order_status'
      AND code = 'approved';

    SELECT look_up_id
    INTO v_po_status_partial_id
    FROM look_up
    WHERE look_up_type = 'purchase_order_status'
      AND code = 'partially_delivered';

    SELECT look_up_id
    INTO v_po_status_delivered_id
    FROM look_up
    WHERE look_up_type = 'purchase_order_status'
      AND code = 'delivered';

    SELECT look_up_id
    INTO v_movement_type_receipt_id
    FROM look_up
    WHERE look_up_type = 'stock_movement_type'
      AND code = 'receipt';

    SELECT look_up_id
    INTO v_movement_status_completed_id
    FROM look_up
    WHERE look_up_type = 'stock_movement_status'
      AND code = 'completed';

    IF v_status_draft_id IS NULL OR v_status_posted_id IS NULL THEN
        RAISE EXCEPTION 'Required supplier_delivery_status lookups are missing.';
    END IF;

    IF v_po_status_approved_id IS NULL OR v_po_status_partial_id IS NULL OR v_po_status_delivered_id IS NULL THEN
        RAISE EXCEPTION 'Required purchase_order_status lookups are missing.';
    END IF;

    IF v_movement_type_receipt_id IS NULL OR v_movement_status_completed_id IS NULL THEN
        RAISE EXCEPTION 'Required stock movement lookups are missing.';
    END IF;

    SELECT *
    INTO v_sd
    FROM supplier_delivery
    WHERE supplier_delivery_id = p_supplier_delivery_id
      AND is_deleted = FALSE
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Supplier delivery % was not found or is deleted.', p_supplier_delivery_id;
    END IF;

    IF v_sd.status_id <> v_status_draft_id THEN
        RAISE EXCEPTION 'Supplier delivery % must be in draft status before posting.', p_supplier_delivery_id;
    END IF;

    SELECT *
    INTO v_po
    FROM purchase_order
    WHERE purchase_order_id = v_sd.purchase_order_id
      AND is_deleted = FALSE
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Purchase order % was not found or is deleted.', v_sd.purchase_order_id;
    END IF;

    IF v_po.supplier_party_id <> v_sd.supplier_id THEN
        RAISE EXCEPTION
            'Supplier delivery supplier % does not match purchase order supplier %.',
            v_sd.supplier_id,
            v_po.supplier_party_id;
    END IF;

    IF v_po.status_id NOT IN (v_po_status_approved_id, v_po_status_partial_id) THEN
        RAISE EXCEPTION
            'Purchase order % is not in an approved/partially delivered status and cannot be received.',
            v_po.purchase_order_id;
    END IF;

    FOR v_item IN
        SELECT
            sdi.supplier_delivery_item_id,
            sdi.purchase_order_item_id,
            sdi.material_id,
            sdi.material_brand_id,
            sdi.uom_id,
            sdi.accepted_quantity,
            poi.purchase_order_id,
            poi.ordered_quantity,
            poi.received_quantity
        FROM supplier_delivery_item sdi
        JOIN purchase_order_item poi
          ON poi.purchase_order_item_id = sdi.purchase_order_item_id
        WHERE sdi.supplier_delivery_id = p_supplier_delivery_id
          AND sdi.is_deleted = FALSE
          AND poi.is_deleted = FALSE
        FOR UPDATE OF sdi, poi
    LOOP
        v_item_count := v_item_count + 1;

        IF v_item.purchase_order_id <> v_sd.purchase_order_id THEN
            RAISE EXCEPTION
                'Supplier delivery item % does not belong to purchase order %.',
                v_item.supplier_delivery_item_id,
                v_sd.purchase_order_id;
        END IF;

        v_remaining_qty := v_item.ordered_quantity - v_item.received_quantity;
        IF v_item.accepted_quantity > v_remaining_qty THEN
            RAISE EXCEPTION
                'Accepted quantity % exceeds remaining quantity % for PO item %.',
                v_item.accepted_quantity,
                v_remaining_qty,
                v_item.purchase_order_item_id;
        END IF;

        IF v_item.accepted_quantity > 0 THEN
            INSERT INTO stock_movement (
                source_id,
                destination_id,
                material_id,
                material_brand_id,
                quantity,
                uom_id,
                movement_type_id,
                status_id,
                movement_date,
                reference_code,
                notes,
                log_date_created,
                log_created_by_account_id,
                log_module_created
            ) VALUES (
                v_sd.supplier_id,
                v_sd.project_id,
                v_item.material_id,
                v_item.material_brand_id,
                v_item.accepted_quantity,
                v_item.uom_id,
                v_movement_type_receipt_id,
                v_movement_status_completed_id,
                COALESCE(v_sd.delivery_date, now()),
                v_sd.supplier_delivery_number,
                v_sd.notes,
                now(),
                COALESCE(p_posted_by_account_id, v_sd.received_by_account_id),
                'supplier_delivery'
            ) RETURNING stock_movement_id INTO v_movement_id;

            UPDATE supplier_delivery_item
            SET stock_movement_id = v_movement_id,
                log_date_updated = now(),
                log_updated_by_account_id = COALESCE(p_posted_by_account_id, v_sd.received_by_account_id),
                log_module_updated = 'supplier_delivery'
            WHERE supplier_delivery_item_id = v_item.supplier_delivery_item_id;

            INSERT INTO stock_balance (
                party_id,
                material_id,
                material_brand_id,
                quantity_on_hand,
                uom_id,
                log_date_created,
                log_created_by_account_id,
                log_module_created
            )
            SELECT
                v_sd.project_id,
                v_item.material_id,
                v_item.material_brand_id,
                0,
                v_item.uom_id,
                now(),
                COALESCE(p_posted_by_account_id, v_sd.received_by_account_id),
                'supplier_delivery'
            WHERE NOT EXISTS (
                SELECT 1
                FROM stock_balance sb
                WHERE sb.party_id = v_sd.project_id
                  AND sb.material_id = v_item.material_id
                  AND sb.uom_id = v_item.uom_id
                  AND (
                      (sb.material_brand_id IS NULL AND v_item.material_brand_id IS NULL)
                      OR sb.material_brand_id = v_item.material_brand_id
                  )
            );

            UPDATE stock_balance
            SET quantity_on_hand = quantity_on_hand + v_item.accepted_quantity,
                log_date_updated = now(),
                log_updated_by_account_id = COALESCE(p_posted_by_account_id, v_sd.received_by_account_id),
                log_module_updated = 'supplier_delivery'
            WHERE party_id = v_sd.project_id
              AND material_id = v_item.material_id
              AND uom_id = v_item.uom_id
              AND (
                  (material_brand_id IS NULL AND v_item.material_brand_id IS NULL)
                  OR material_brand_id = v_item.material_brand_id
              );

            INSERT INTO stock_layer (
                party_id,
                material_id,
                material_brand_id,
                uom_id,
                quantity_received,
                quantity_available,
                receive_date,
                source_movement_id,
                log_date_created,
                log_created_by_account_id,
                log_module_created
            ) VALUES (
                v_sd.project_id,
                v_item.material_id,
                v_item.material_brand_id,
                v_item.uom_id,
                v_item.accepted_quantity,
                v_item.accepted_quantity,
                COALESCE(v_sd.delivery_date, now()),
                v_movement_id,
                now(),
                COALESCE(p_posted_by_account_id, v_sd.received_by_account_id),
                'supplier_delivery'
            );

            UPDATE purchase_order_item
            SET received_quantity = received_quantity + v_item.accepted_quantity,
                log_date_updated = now(),
                log_updated_by_account_id = COALESCE(p_posted_by_account_id, v_sd.received_by_account_id),
                log_module_updated = 'supplier_delivery'
            WHERE purchase_order_item_id = v_item.purchase_order_item_id;

            v_posted_item_count := v_posted_item_count + 1;
        END IF;
    END LOOP;

    IF v_item_count = 0 THEN
        RAISE EXCEPTION 'Supplier delivery % has no active line items to post.', p_supplier_delivery_id;
    END IF;

    IF v_posted_item_count = 0 THEN
        RAISE EXCEPTION 'Supplier delivery % has no accepted quantities to post.', p_supplier_delivery_id;
    END IF;

    SELECT EXISTS (
        SELECT 1
        FROM purchase_order_item poi
        WHERE poi.purchase_order_id = v_sd.purchase_order_id
          AND poi.is_deleted = FALSE
          AND poi.received_quantity < poi.ordered_quantity
    )
    INTO v_has_remaining;

    UPDATE purchase_order
    SET status_id = CASE WHEN v_has_remaining THEN v_po_status_partial_id ELSE v_po_status_delivered_id END,
        log_date_updated = now(),
        log_updated_by_account_id = COALESCE(p_posted_by_account_id, v_sd.received_by_account_id),
        log_module_updated = 'supplier_delivery'
    WHERE purchase_order_id = v_sd.purchase_order_id;

    UPDATE supplier_delivery
    SET status_id = v_status_posted_id,
        posted_at = now(),
        posted_by_account_id = COALESCE(p_posted_by_account_id, v_sd.received_by_account_id),
        log_date_updated = now(),
        log_updated_by_account_id = COALESCE(p_posted_by_account_id, v_sd.received_by_account_id),
        log_module_updated = 'supplier_delivery'
    WHERE supplier_delivery_id = p_supplier_delivery_id;

    RETURN p_supplier_delivery_id;
END;
$$;