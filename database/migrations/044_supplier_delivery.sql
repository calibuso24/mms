RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_po_supplier_id BIGINT;
BEGIN
    SELECT supplier_party_id
    INTO v_po_supplier_id
    FROM purchase_order
    WHERE purchase_order_id = NEW.purchase_order_id
      AND is_deleted = FALSE;

    IF v_po_supplier_id IS NULL THEN
        RAISE EXCEPTION 'Purchase order % was not found or is deleted.', NEW.purchase_order_id;
    END IF;

    IF NEW.supplier_id <> v_po_supplier_id THEN
        RAISE EXCEPTION
            'Supplier party % does not match purchase order supplier % for PO %.',
            NEW.supplier_id,
            v_po_supplier_id,
            NEW.purchase_order_id;
    END IF;

    RETURN NEW;
END;
$$;


