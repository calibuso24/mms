CREATE OR REPLACE FUNCTION validate_supplier_delivery_purchase_order()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_po RECORD;
    v_sd RECORD;
BEGIN
    SELECT supplier_party_id, project_id
    INTO v_po
    FROM purchase_order
    WHERE purchase_order_id = NEW.purchase_order_id
      AND is_deleted = FALSE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Purchase order % was not found or is deleted.', NEW.purchase_order_id;
    END IF;

    SELECT supplier_id, project_id
    INTO v_sd
    FROM supplier_delivery
    WHERE supplier_delivery_id = NEW.supplier_delivery_id
      AND is_deleted = FALSE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Supplier delivery % was not found or is deleted.', NEW.supplier_delivery_id;
    END IF;

    IF v_po.supplier_party_id <> v_sd.supplier_id THEN
        RAISE EXCEPTION
            'Supplier delivery supplier % does not match purchase order supplier %.',
            v_sd.supplier_id,
            v_po.supplier_party_id;
    END IF;

    IF v_po.project_id <> v_sd.project_id THEN
        RAISE EXCEPTION
            'Supplier delivery project % does not match purchase order project %.',
            v_sd.project_id,
            v_po.project_id;
    END IF;

    RETURN NEW;
END;
$$;

