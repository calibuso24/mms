CREATE TABLE material_specification (
    material_specification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id BIGINT NOT NULL UNIQUE REFERENCES material(material_id) ON DELETE CASCADE,
    primary_size TEXT,
    secondary_size TEXT,
    alternate_size TEXT,
    thickness_or_gauge TEXT,
    width TEXT,
    length TEXT,
    schedule TEXT,
    pressure_or_load_rating TEXT,
    standard TEXT,
    pack_size TEXT,
    additional_specification TEXT,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    log_date_created TIMESTAMPTZ,
    log_date_updated TIMESTAMPTZ,
    log_created_by_account_id BIGINT,
    log_updated_by_account_id BIGINT,
    log_date_deleted TIMESTAMPTZ,
    log_deleted_by_account_id BIGINT,
    log_module_created TEXT,
    log_module_updated TEXT
);
